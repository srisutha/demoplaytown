export function getMessagesByState(state: unknown): string[] {
  const s = toStr(state).trim().toLowerCase();
  for (const b of BRANCHES) {
    if (b.states === null || b.states.includes(s)) return b.messages;
  }
  return BRANCHES[BRANCHES.length - 1].messages;
}

/** Random index into the message list for a state (PHP array_rand). */
export function getWelcomeMessageId(state: unknown): number {
  return rand(0, getMessagesByState(state).length - 1);
}

/** isset($messages[$id]) ? $messages[$id] : '' */
export function getWelcomeMessageById(state: unknown, id: unknown): string {
  const messages = getMessagesByState(state);
  const idx = typeof id === 'number' ? id : /^-?\d+$/.test(toStr(id)) ? Number(id) : NaN;
  return Number.isInteger(idx) && idx >= 0 && idx < messages.length ? messages[idx] : '';
}
